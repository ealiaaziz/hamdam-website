#!/usr/bin/env node
// Regenerates src/data/releases.ts from the two places release notes actually
// exist, so nothing on the What's New page is retyped and the Persian half is
// never authored here.
//
// Two sources, and the split matters:
//
//   1. The LIVE App Store listing (itunes.apple.com/lookup). Apple serves the
//      release notes for the current version only, in the one bilingual field
//      App Store Connect has: English, two blank lines, Farsi. That is the
//      authority for whatever version is live right now, and it is the only
//      source that cannot be stale.
//   2. `docs/app-store/v*-whats-new.md` in the sibling hamdam-ios repository,
//      which holds the same field for earlier releases inside a fenced block.
//      Apple does not publish an older version's notes anywhere a script can
//      read, so once a release is superseded this repository is the record.
//
// Consequence worth stating plainly: a release whose notes were never written
// into hamdam-ios is unrecoverable here. 1.3.1 is exactly that case, and it is
// why the page skips from 1.3 to 1.3.2. Recovering it means reading App Store
// Connect by hand and adding the entry.
//
// Release dates come from the listing (`currentVersionReleaseDate`) for the
// live version and from FACTS.md for the earlier ones. They are UTC dates, as
// Apple reports them.
//
// Usage:
//   node scripts/extract-releases.mjs [--ios-repo ../hamdam-ios] [--write]
//
// Without --write it prints the file to stdout so a diff can be read first.

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const args = process.argv.slice(2);
const iosRepo = valueOf('--ios-repo') ?? '../hamdam-ios';
const write = args.includes('--write');
const APP_ID = '6784461990';

function valueOf(flag) {
  const i = args.indexOf(flag);
  return i === -1 ? undefined : args[i + 1];
}

/**
 * Splits one App Store Connect `whatsNew` field into its two halves and their
 * paragraphs. The field is English, then two blank lines, then Farsi: there is
 * no Persian store locale, so both languages share the single field. See
 * hamdam-ios `docs/app-store/pre-upload-checklist.md` section 1.
 */
export function splitWhatsNew(raw) {
  const text = raw.replace(/\r\n/g, '\n').trim();
  const halves = text.split(/\n[ \t]*\n[ \t]*\n/);
  if (halves.length < 2) throw new Error('whatsNew field has no English/Farsi separator');
  const paragraphs = (half) =>
    half
      .split(/\n[ \t]*\n/)
      .map((p) => p.replace(/\s*\n\s*/g, ' ').trim())
      .filter(Boolean);
  return {
    notesEn: paragraphs(halves[0]),
    notesFa: paragraphs(halves.slice(1).join('\n\n\n')),
  };
}

/** Pulls the one fenced code block out of a v*-whats-new.md file. */
export function fencedBlock(markdown) {
  const m = markdown.match(/```\n([\s\S]*?)\n```/);
  if (!m) throw new Error('no fenced block found');
  return m[1];
}

async function liveListing() {
  const res = await fetch(`https://itunes.apple.com/lookup?id=${APP_ID}&country=us`);
  if (!res.ok) throw new Error(`lookup failed: ${res.status}`);
  const body = await res.json();
  if (!body.resultCount) throw new Error('lookup returned no result');
  return body.results[0];
}

function isoDate(stamp) {
  return stamp.slice(0, 10);
}

const listing = await liveListing();
const live = {
  version: listing.version,
  iso: isoDate(listing.currentVersionReleaseDate),
  ...splitWhatsNew(listing.releaseNotes),
  source: 'itunes.apple.com/lookup, the live listing',
};

// Earlier releases, newest first. Each names the file its text comes from and
// the date's authority; nothing here is typed from memory.
const ARCHIVED = [
  { version: '1.3', iso: '2026-08-27', file: 'v1.3-whats-new.md' },
  { version: '1.2', iso: '2026-08-17', file: 'v1.2-whats-new.md' },
];

const archived = ARCHIVED.map((entry) => {
  const path = join(iosRepo, 'docs/app-store', entry.file);
  const raw = fencedBlock(readFileSync(path, 'utf8'));
  return {
    version: entry.version,
    iso: entry.iso,
    ...splitWhatsNew(raw),
    source: `hamdam-ios docs/app-store/${entry.file}`,
  };
});

const releases = [live, ...archived.filter((r) => r.version !== live.version)];

const quote = (s) => JSON.stringify(s);
const paragraphs = (list) => list.map((p) => `      ${quote(p)},`).join('\n');

const body = releases
  .map(
    (r) => `  {
    version: ${quote(r.version)},
    iso: ${quote(r.iso)},
    source: ${quote(r.source)},
    notesEn: [
${paragraphs(r.notesEn)}
    ],
    notesFa: [
${paragraphs(r.notesFa)}
    ],
  },`,
  )
  .join('\n');

const file = `// GENERATED by scripts/extract-releases.mjs. Do not hand edit.
//
// Every string below is the App Store Connect "What's New in This Version"
// field, byte exact. The Farsi half is Ealia's own published text: it is copied
// by script from the live listing or from hamdam-ios, never authored,
// translated or retyped here, which is the standing rule for Persian in this
// repository.
//
// The field is one bilingual blob because App Store Connect has no Persian
// store locale, so each release carries English paragraphs then Farsi ones.
// Regenerate rather than edit:
//
//   node scripts/extract-releases.mjs --write
//
// and verify the live version against the store afterwards:
//
//   npm run check:release
//
// Newest first. What is NOT here, and why: 1.3.1 (30 August 2026) shipped and
// its notes were never written into hamdam-ios, and Apple publishes only the
// current version's notes, so there is no source a script can read. Same for
// 1.0, 1.0.1, 1.1 and 1.1.1. Adding any of them means reading App Store
// Connect by hand. Inventing them is not an option.

export interface Release {
  /** Marketing version, exactly as the App Store reports it. */
  readonly version: string;
  /** Release date, UTC, as Apple reports it. */
  readonly iso: string;
  /** Where this entry's text was read from. */
  readonly source: string;
  /** English paragraphs. The first is the release's headline. */
  readonly notesEn: readonly string[];
  /** Farsi paragraphs, same order, Ealia's own text. */
  readonly notesFa: readonly string[];
}

export const RELEASES: readonly Release[] = [
${body}
] as const;
`;

if (write) {
  writeFileSync('src/data/releases.ts', file);
  process.stderr.write(`wrote src/data/releases.ts with ${releases.length} releases\n`);
} else {
  process.stdout.write(file);
}
